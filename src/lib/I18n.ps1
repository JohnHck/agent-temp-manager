# Agent Temp Manager - message catalog (pt-BR, en-US).
#
# Rules:
#  * Only TEXT lives here. Engine decisions never depend on it: reason/flag/class/status codes (e.g.
#    COBERTURA_DE_PROCESSOS_INCOMPLETA, ACTIVE_EVIDENCE, AUDITADO) are stable identifiers, identical in every language.
#  * Language: -Lang parameter > ATM_LANG environment variable > current UI culture. pt* -> pt-BR; anything else
#    (including unknown values) -> en-US.
#  * Safe fallback: missing key in the chosen language -> en-US -> "[key]". Formatting never throws.
Set-StrictMode -Version 2.0


function Resolve-AtmLanguage {
    param([string]$Requested)
    foreach ($c in @($Requested, $env:ATM_LANG, [Globalization.CultureInfo]::CurrentUICulture.Name)) {
        if ([string]::IsNullOrWhiteSpace($c)) { continue }
        if ($c -match '^(?i)pt') { return 'pt-BR' }
        return 'en-US'
    }
    return 'en-US'
}

function Set-AtmLanguage { param([string]$Requested) $script:AtmLanguage = Resolve-AtmLanguage -Requested $Requested }
function Get-AtmLanguage { return $script:AtmLanguage }

function Get-AtmText {
    # Get-AtmText <key> [format args...]
    $key = [string]$args[0]
    $fmtArgs = @()
    if ($args.Count -gt 1) { $fmtArgs = @($args[1..($args.Count - 1)]) }
    $tpl = $null
    $cat = $script:AtmMessages[$script:AtmLanguage]
    if ($cat -and $cat.ContainsKey($key)) { $tpl = $cat[$key] }
    if ($null -eq $tpl -and $script:AtmMessages['en-US'].ContainsKey($key)) { $tpl = $script:AtmMessages['en-US'][$key] }
    if ($null -eq $tpl) { return "[$key]" }
    if ($fmtArgs.Count -eq 0) { return $tpl }
    try { return ($tpl -f $fmtArgs) } catch { return ($tpl + ' ' + ($fmtArgs -join ' ')) }
}

